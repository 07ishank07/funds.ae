// Static job pages: frontend_demo/jobs/<slug>.html, one per open job posted through the Careers section of
// Sanity (jobs with a slug and a description), built from backend/templates/job.html.
//
// Every value is HTML-escaped here; the description becomes paragraphs and the requirements a list, never
// markup. The only outbound links are the employer's apply page and website (https checked). A file is
// written only when its content changes, and only files carrying the generated marker are ever deleted.

import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, unlinkSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { BACKEND_DIR, JOB_PAGES_DIR } from '../config.js';
import { escapeHtml } from './storyPages.js';
import { initialsFor } from './employers.js';
import { log } from '../lib/logger.js';

export const JOB_GENERATED_MARKER = '<!-- generated by backend/src/pipeline/jobPages.js';
export const JOB_TEMPLATE = path.join(BACKEND_DIR, 'templates', 'job.html');
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const DATE = new Intl.DateTimeFormat('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'Asia/Dubai' });
const NUMBER = new Intl.NumberFormat('en-US');

const httpsUrl = (value) => (/^https:\/\/[^\s"'<>]+$/i.test(String(value || '')) ? String(value) : null);
const dateText = (iso) => {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? '' : DATE.format(d);
};

/** "AED 25,000–35,000 / month" */
export function salaryText(salary) {
  if (!salary || !Number.isInteger(salary.from)) return '';
  const range = Number.isInteger(salary.to) && salary.to !== salary.from ? `${NUMBER.format(salary.from)}–${NUMBER.format(salary.to)}` : NUMBER.format(salary.from);
  return `${salary.currency || ''} ${range}${salary.period ? ` / ${salary.period}` : ''}`.trim();
}

function facts(job) {
  const rows = [
    ['Salary', salaryText(job.salary)],
    ['Visa', job.visa],
    ['Type', job.employmentType],
    ['Work mode', job.workMode],
    ['Level', job.seniority],
    ['Function', job.department],
    ['Regulator', job.regulator],
    ['Posted', dateText(job.postedAt)],
    ['Apply by', job.expiresAt ? dateText(job.expiresAt) : '']
  ].filter(([, value]) => value);
  return rows.map(([label, value]) => `<div><dt>${escapeHtml(label)}</dt><dd>${escapeHtml(value)}</dd></div>`).join('');
}

const paragraphs = (text) =>
  String(text || '')
    .split(/\n\s*\n/)
    .map((p) => p.replace(/\s+/g, ' ').trim())
    .filter(Boolean)
    .map((p) => `      <p>${escapeHtml(p)}</p>\n`)
    .join('');

function logo(job) {
  const src = httpsUrl(job.logoUrl);
  if (src) return `<span class="job-logo"><img src="${escapeHtml(src)}" alt="${escapeHtml(job.company)} logo" loading="lazy" referrerpolicy="no-referrer"></span>`;
  return `<span class="job-logo" aria-hidden="true">${escapeHtml(initialsFor(job.company))}</span>`;
}

function employerSection(job, employer) {
  const website = httpsUrl(employer?.website || job.companyUrl);
  if (!employer?.description && !website) return '';
  const about = employer?.description ? `      <p>${escapeHtml(employer.description)}</p>\n` : '';
  const link = website ? `      <p><a href="${escapeHtml(website)}" target="_blank" rel="noopener noreferrer">${escapeHtml(job.company)} website</a></p>\n` : '';
  return `    <section class="section" aria-label="About the employer">\n      <h2>About ${escapeHtml(job.company)}</h2>\n${about}${link}    </section>\n`;
}

/**
 * One job page as HTML.
 * @param {object} job  a job record (src/pipeline/jobs.js) posted through Sanity
 * @param {{template:string, employer?:object, publicBaseUrl?:string}} opts
 */
export function renderJobPage(job, { template, employer = null, publicBaseUrl = '' }) {
  if (!SLUG.test(job.slug || '')) throw new Error(`Job ${job.jobId} has no valid slug.`);
  const applyUrl = httpsUrl(job.url);
  if (!applyUrl) throw new Error(`Job ${job.jobId} has no https apply link.`);
  const canonical = publicBaseUrl ? `${publicBaseUrl}frontend_demo/jobs/${job.slug}.html` : '';
  const summary = `${job.title} at ${job.company}, ${job.location}.${job.salary ? ` ${salaryText(job.salary)}.` : ''}`;
  const requirements = (job.requirements || []).filter(Boolean);
  const values = {
    pageTitle: escapeHtml(`${job.title}, ${job.company}`),
    pageDescription: escapeHtml(summary),
    canonical: canonical ? `<link rel="canonical" href="${escapeHtml(canonical)}">\n<meta property="og:url" content="${escapeHtml(canonical)}">\n` : '',
    logo: logo(job),
    title: escapeHtml(job.title),
    company: escapeHtml(job.company),
    location: escapeHtml(job.location),
    facts: facts(job),
    applyUrl: escapeHtml(applyUrl),
    description: paragraphs(job.description),
    requirements: requirements.length
      ? `    <section class="section" aria-label="Requirements">\n      <h2>Requirements</h2>\n      <ul>${requirements.map((r) => `<li>${escapeHtml(r)}</li>`).join('')}</ul>\n    </section>\n`
      : '',
    employer: employerSection(job, employer)
  };
  return template.replace(/\{\{(\w+)\}\}/g, (match, key) => {
    if (!Object.hasOwn(values, key)) throw new Error(`job.html uses an unknown placeholder ${match}.`);
    return values[key];
  });
}

/**
 * Writes a page per open posted job and removes generated pages of jobs that are no longer open.
 * @param {object[]} jobs  open job records, newest first (on a slug clash the newest keeps the slug)
 * @param {{dir?:string, employers?:Map<string,object>, publicBaseUrl?:string}} opts  employers: by employerId
 * @returns {{pages:number, written:number, removed:number}}
 */
export function writeJobPages(jobs, { dir = JOB_PAGES_DIR, employers = new Map(), publicBaseUrl = '' } = {}) {
  const template = readFileSync(JOB_TEMPLATE, 'utf8');
  const keep = new Set();
  let written = 0;
  const posted = jobs.filter((j) => j.slug && j.description);
  if (posted.length) mkdirSync(dir, { recursive: true });
  for (const job of posted) {
    const file = `${job.slug}.html`;
    if (keep.has(file)) {
      log.warn('jobs.page.slug-clash', { job: job.jobId, slug: job.slug });
      continue;
    }
    keep.add(file);
    const html = renderJobPage(job, { template, employer: employers.get(job.employerId), publicBaseUrl });
    const target = path.join(dir, file);
    if (existsSync(target) && readFileSync(target, 'utf8') === html) continue;
    const tmp = `${target}.${process.pid}.tmp`;
    writeFileSync(tmp, html, 'utf8');
    renameSync(tmp, target);
    written++;
  }
  let removed = 0;
  if (existsSync(dir)) {
    for (const file of readdirSync(dir)) {
      if (!file.endsWith('.html') || keep.has(file)) continue;
      const target = path.join(dir, file);
      if (readFileSync(target, 'utf8').slice(0, 400).includes(JOB_GENERATED_MARKER)) {
        unlinkSync(target);
        removed++;
      }
    }
  }
  return { pages: keep.size, written, removed };
}

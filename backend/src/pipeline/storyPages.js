// Static story pages: frontend_demo/news/<slug>.html, one per published story, built from
// backend/templates/story.html so search engines get a real page per story on GitHub Pages.
//
// Every value is HTML-escaped here. The only outbound links are the publishers' own
// (http/https checked) and the site's relative pages; publisher images appear only when
// the story DTO carries one (the source allows images, or the editor's image is
// rights-cleared). A file is written only when its content changes, so unchanged stories
// make no git noise, and only files carrying the generated marker are ever deleted.

import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, unlinkSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { BACKEND_DIR, STORY_PAGES_DIR } from '../config.js';

export const GENERATED_MARKER = '<!-- generated by backend/src/pipeline/storyPages.js';
export const STORY_TEMPLATE = path.join(BACKEND_DIR, 'templates', 'story.html');
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const TAG_ID = /^[a-z0-9][a-z0-9-]{0,60}$/;
const DATE = new Intl.DateTimeFormat('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'Asia/Dubai' });

export function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

const httpUrl = (value) => (/^https?:\/\/[^\s"'<>]+$/i.test(String(value || '')) ? String(value) : null);
const httpsUrl = (value) => (/^https:\/\/[^\s"'<>]+$/i.test(String(value || '')) ? String(value) : null);
const dateText = (iso) => {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? '' : DATE.format(d);
};

function tagList(story) {
  const chips = [];
  if (story.transactionType) chips.push(`<li><span class="deal">${escapeHtml(story.transactionType.label)}</span></li>`);
  const linked = (param, tags) =>
    tags
      .filter((t) => TAG_ID.test(t.id))
      .forEach((t) => chips.push(`<li><a href="../News.dc.html?${param}=${t.id}">${escapeHtml(t.label)}</a></li>`));
  linked('capital', story.capitalTypes);
  linked('asset', story.assetClasses);
  linked('geo', story.geography);
  return chips.length ? `    <ul class="tags" aria-label="Categories">${chips.join('')}</ul>\n` : '';
}

function imageBlock(story) {
  const src = httpsUrl(story.imageUrl);
  if (!src) return '';
  const credit = story.imageCredit || `Image: ${story.source}`;
  return `    <figure><img src="${escapeHtml(src)}" alt="" loading="lazy" referrerpolicy="no-referrer"><figcaption>${escapeHtml(credit)}</figcaption></figure>\n`;
}

function otherOutlets(story) {
  const items = story.sources.slice(1).filter((s) => httpUrl(s.url));
  if (!items.length) return '';
  const rows = items
    .map((s) =>
      `<li><a href="${escapeHtml(s.url)}" target="_blank" rel="noopener noreferrer">${escapeHtml(s.title || s.source)}</a>` +
      `<span>${escapeHtml(s.source)} · ${escapeHtml(dateText(s.publishedAt))}</span></li>`)
    .join('');
  return `    <section class="others" aria-label="Also reported by"><h2>Also reported by</h2><ul>${rows}</ul></section>\n`;
}

/**
 * One story page as HTML.
 * @param {object} story  story DTO (src/contracts/serializers.js)
 * @param {{template:string, publicBaseUrl?:string, seo?:{title?:string, description?:string}}} opts
 */
export function renderStoryPage(story, { template, publicBaseUrl = '', seo = {} }) {
  if (!SLUG.test(story.slug || '')) throw new Error(`Story ${story.id} has no valid slug.`);
  const sourceUrl = httpUrl(story.url);
  if (!sourceUrl) throw new Error(`Story ${story.id} has no link to the original article.`);
  const realEstate = story.assetClasses.length > 0;
  const canonical = publicBaseUrl ? `${publicBaseUrl}frontend_demo/news/${story.slug}.html` : '';
  const values = {
    pageTitle: escapeHtml((seo.title || story.headline).trim()),
    pageDescription: escapeHtml((seo.description || story.summary || '').trim()),
    canonical: canonical ? `<link rel="canonical" href="${escapeHtml(canonical)}">\n<meta property="og:url" content="${escapeHtml(canonical)}">\n` : '',
    sectionHref: realEstate ? '../News.dc.html' : '../this.html',
    sectionLabel: realEstate ? 'Real Estate Capital News' : 'Funds.ae news',
    tags: tagList(story),
    headline: escapeHtml(story.headline),
    sourceName: escapeHtml(story.source),
    sourceUrl: escapeHtml(sourceUrl),
    publishedIso: escapeHtml(story.publishedAt),
    publishedDate: escapeHtml(dateText(story.publishedAt)),
    image: imageBlock(story),
    summary: escapeHtml(story.summary || ''),
    otherSources: otherOutlets(story)
  };
  return template.replace(/\{\{(\w+)\}\}/g, (match, key) => {
    if (!Object.hasOwn(values, key)) throw new Error(`story.html uses an unknown placeholder ${match}.`);
    return values[key];
  });
}

/**
 * Writes a page per story and removes generated pages of stories that are no longer public.
 * @param {object[]} stories  story DTOs, newest first (on a slug clash the newest keeps the slug)
 * @returns {{pages:number, written:number, removed:number}}
 */
export function writeStoryPages(stories, { dir = STORY_PAGES_DIR, publicBaseUrl = '', seoById = new Map() } = {}) {
  const template = readFileSync(STORY_TEMPLATE, 'utf8');
  mkdirSync(dir, { recursive: true });
  const keep = new Set();
  let written = 0;
  for (const story of stories) {
    const file = `${story.slug}.html`;
    keep.add(file);
    const html = renderStoryPage(story, { template, publicBaseUrl, seo: seoById.get(story.id) });
    const target = path.join(dir, file);
    if (existsSync(target) && readFileSync(target, 'utf8') === html) continue;
    const tmp = `${target}.${process.pid}.tmp`;
    writeFileSync(tmp, html, 'utf8');
    renameSync(tmp, target);
    written++;
  }
  let removed = 0;
  for (const file of readdirSync(dir)) {
    if (!file.endsWith('.html') || keep.has(file)) continue;
    const target = path.join(dir, file);
    if (readFileSync(target, 'utf8').slice(0, 400).includes(GENERATED_MARKER)) {
      unlinkSync(target);
      removed++;
    }
  }
  return { pages: keep.size, written, removed };
}
